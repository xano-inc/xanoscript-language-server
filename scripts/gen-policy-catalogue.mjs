#!/usr/bin/env node
// Regenerate parser/policy/catalogueSnapshot.js from the check catalogue the platform serves. Xano
// maintainers run it against the platform's catalogue file:
//
//   npm run gen:policy-catalogue -- path/to/policy-catalogue.json
//
// `xano policy catalogue -o json` (or `GET /api:meta/workspace/{id}/policy/check`) from an instance
// answers the same catalogue (`items`, `templates`, `recipes`,
// `document` and the rest); only `items` (each check with its params and `uses`) and `document`
// are kept.
//
// The snapshot is what the language server checks a policy against when its host has
// no live catalogue: the Node server (editors) and offline tools. The Xano editor never loads it; it
// sends the instance's own catalogue. Regenerate it whenever the platform's catalogue changes (a check
// or a param added, renamed or removed).
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { fileURLToPath } from "node:url";

export const SNAPSHOT = fileURLToPath(
  new URL("../parser/policy/catalogueSnapshot.js", import.meta.url)
);

/**
 * The module text for a catalogue response: its checks, sorted by id, and its `document` (the
 * policy file's own fields), as served (templates are for creating policies, not for reading one), and
 * the day it was taken, which a finding made against it quotes.
 * @param {Object|Object[]} catalogue
 * @param {string} generatedAt YYYY-MM-DD
 */
export function renderSnapshot(catalogue, generatedAt) {
  const items = [...(Array.isArray(catalogue) ? catalogue : catalogue.items ?? [])];
  if (!items.length || items.some((item) => typeof item?.id !== "string")) {
    throw new Error("Expected a policy check catalogue: {items: [{id, params, ...}]}.");
  }
  items.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return [
    "// Generated by scripts/gen-policy-catalogue.mjs from the platform's policy check catalogue",
    "// (`xano policy catalogue -o json`). Do not edit by hand: regenerate it.",
    "export default " +
      JSON.stringify({ generated_at: generatedAt, items, document: catalogue.document ?? null }, null, 2) +
      ";",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const from = process.argv[2];
  const text = readFileSync(from && from !== "-" ? from : 0, "utf8");
  const module = renderSnapshot(JSON.parse(text), new Date().toISOString().slice(0, 10));
  writeFileSync(SNAPSHOT, module);
  const count = (module.match(/^ {6}"id": /gm) ?? []).length;
  console.log(`Wrote ${SNAPSHOT} (${count} checks).`);
}
